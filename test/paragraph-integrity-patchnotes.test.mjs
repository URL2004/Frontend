import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
test('paragraph integrity notes disclose detector limitations and preserve earlier releases', () => {
  const html = readFileSync(new URL('../pages/admin.html', import.meta.url), 'utf8');
  assert.match(html, /휴머나이징 v2\.5\.105 · AI 감지 v1\.52/);
  assert.match(html, /v2\.5\.74 · 감지 v1\.43/);
  assert.match(html, /113건은 개발·회귀 자료/);
  const timeline = html.split('<div class="gp-admin-patch-timeline">')[1];
  const current = timeline.split('<span class="gp-admin-patch-version">v2.5.90</span>')[1].split('</details>')[0];
  assert.match(current, /v2\.5\.90/);
  assert.match(current, /Backend 159878b/);
  assert.match(current, /2,776개/);
  assert.match(current, /장문 전체 신규 생성은 미완료/);
  assert.match(current, /단계형 확인 실험 기능은 OFF/);
  assert.match(current, /후보라는 이유만으로 오류를 확정하거나 자동 수정하지 않습니다/);
  assert.match(current, /모델·요금·전달·과금 정책은 변경하지 않았습니다/);
  assert.match(timeline, /두 번째의 정도 표현 누락은 실패/);
  assert.ok(timeline.indexOf('v2.5.90') < timeline.indexOf('v2.5.80–89'));
  assert.ok(timeline.indexOf('v2.5.80–89') < timeline.indexOf('v2.5.78–79'));
  assert.ok(timeline.indexOf('v2.5.77') < timeline.indexOf('v2.5.76'));
  assert.ok(timeline.indexOf('v2.5.76') < timeline.indexOf('v2.5.75'));
  assert.match(timeline, /점수 산식과 이력 보정은 그대로/);
  assert.match(timeline, /세 번째 전체 신규 생성은 하지 않았으며/);
  const latest = timeline.split('<span class="gp-admin-patch-version">v2.5.74')[1].split('</details>')[0];
  assert.match(latest, /gp-admin-patch-state is-live">운영 반영/);
  assert.match(latest, /백엔드 2,160개, 프런트 348개/);
  assert.match(latest, /전량 신규 생성은 아닙니다/);
  assert.match(latest, /일부 진단 오탐/);
  assert.doesNotMatch(latest, /배포 보류|진행 중/);
  assert.match(html, /원문·결과 97쌍 전문 대조/);
  assert.match(html, /사람 블라인드 평가, 감지 정확도 또는 전체 문장 품질의 무오류 보장은 아닙니다/);
  assert.match(html, /Backend dc3ae90/);
  assert.match(html, /Backend b0b8efd/);
  assert.match(html, /해결 완료로 표시하지 않습니다/);
  assert.match(html, /Backend 23a3624/);
  const count = [...html.matchAll(/<details class="gp-admin-patch-release"/g)].length;
  assert.equal(count, 101);
  assert.match(html, /101개 변경 묶음/);
  assert.match(html, /2026\.06\.04 — 10\.08/);
  assert.match(html, /Backend 80e7543/);
  assert.match(html, /원본 PDF 대조가 없는 상태/);
  assert.match(html, /페이지 간 논리적 행 복원/);
  assert.match(html, /대표 본문 12개/);
  assert.match(html, /미시도 조각 수/);
  assert.match(html, /신규 유료 모델 재실행은 하지 않았으며/);
  assert.match(html, /v2\.5\.53 · 감지 v1\.34/);
  assert.match(html, /실패 응답과 채택하지 않은 후보/);
});
